// Command lexicon manages a portable Lexicon bundle. It intentionally owns
// installation metadata only: the knowledge database remains owned by the
// composed Lexicon application.
package main

import (
	"encoding/json"
	"errors"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"runtime"
	"strings"
	"time"
)

const registryVersion = 1

type registry struct {
	Version    int         `json:"version"`
	Global     target      `json:"global"`
	Workspaces []workspace `json:"workspaces"`
}
type target struct {
	Instance string `json:"instance"`
}
type workspace struct {
	Root     string    `json:"root"`
	Instance string    `json:"instance"`
	Projects []project `json:"projects"`
}
type project struct {
	Root     string `json:"root"`
	Instance string `json:"instance"`
}

func main() {
	if err := execute(os.Args[1:]); err != nil {
		fmt.Fprintln(os.Stderr, "lexicon:", err)
		os.Exit(1)
	}
}

func execute(args []string) error {
	if len(args) == 0 {
		return errors.New("command required: deck|init|registry|doctor")
	}
	switch args[0] {
	case "deck":
		return deckCommand(args[1:])
	case "setup":
		return setupCommand(args[1:])
	case "init":
		return initCommand(args[1:])
	case "registry":
		return registryCommand(args[1:])
	case "doctor":
		return doctorCommand(args[1:])
	default:
		return fmt.Errorf("unknown command %q", args[0])
	}
}

func setupCommand(args []string) error {
	if len(args) == 0 {
		return errors.New("setup target required: nvim")
	}
	if args[0] != "nvim" {
		return fmt.Errorf("unknown setup target %q", args[0])
	}
	f := flag.NewFlagSet("aideck setup nvim", flag.ContinueOnError)
	cards := f.String("cards", "lens", "comma-separated AI Deck cards")
	config := f.String("nvim-config", defaultNvimConfig(), "Neovim configuration root")
	lens := f.String("lens-plugin", filepath.Join(bundleRoot(), "apps", "lens", "nvim"), "Lens Neovim plugin root")
	splice := f.String("splice-plugin", filepath.Join(bundleRoot(), "apps", "splice", "nvim"), "Splice Neovim plugin root")
	if err := f.Parse(args[1:]); err != nil {
		return err
	}
	selected, err := resolveCards(*cards)
	if err != nil {
		return err
	}
	if err := os.MkdirAll(filepath.Join(*config, "lua", "plugins"), 0o755); err != nil {
		return err
	}
	return os.WriteFile(filepath.Join(*config, "lua", "plugins", "aideck.lua"), []byte(nvimSpec(selected, *lens, *splice)), 0o600)
}

func nvimSpec(cards []string, lensPath, splicePath string) string {
	specs := make([]string, 0, 2)
	for _, card := range cards {
		if card == "lens" {
			specs = append(specs, "{ dir = "+fmt.Sprintf("%q", filepath.ToSlash(lensPath))+", name = 'aideck-lens.nvim', keys = { { '<leader>al', '<cmd>LensOpen<cr>', desc = 'AI Deck: Lens' } }, config = function() require('inspector').setup({ view = 'side' }) end }")
		}
		if card == "splice" {
			specs = append(specs, "{ dir = "+fmt.Sprintf("%q", filepath.ToSlash(splicePath))+", name = 'aideck-splice.nvim', keys = { { '<leader>po', function() require('splice').overview() end, desc = 'AI Deck: Splice overview' }, { '<leader>pe', function() require('splice').edit() end, mode = 'v', desc = 'AI Deck: Splice edit' }, { '<leader>pg', function() require('splice').generate() end, desc = 'AI Deck: Splice generate' } }, config = function() require('splice').setup({}) end }")
		}
	}
	if len(specs) == 0 {
		return "-- Generated by AI Deck. No selected card currently needs a Neovim view.\nreturn {}\n"
	}
	return "-- Generated by AI Deck. This file is safe to replace.\nreturn { " + strings.Join(specs, ", ") + " }\n"
}

// deck validates a portable AI Deck selection. A deck is only a manifest of
// independently runnable cards; it never merges their state or authority.
func deckCommand(args []string) error {
	f := flag.NewFlagSet("aideck deck", flag.ContinueOnError)
	cards := f.String("cards", "lexicon", "comma-separated cards: lexicon,splice,scry,trace,lens,atlas")
	if err := f.Parse(args); err != nil {
		return err
	}
	if len(f.Args()) != 0 {
		return errors.New("deck accepts no positional arguments")
	}
	selected, err := resolveCards(*cards)
	if err != nil {
		return err
	}
	return json.NewEncoder(os.Stdout).Encode(map[string]any{"version": "aideck.deck.v1", "cards": selected})
}

var cardDependencies = map[string][]string{
	"lexicon": nil,
	"splice":  nil,
	// Scry's `observe` contract reads an explicit watch manifest directly.
	// Its Lexicon review integration is optional, never a deck dependency.
	"scry":  nil,
	"trace": nil,
	"lens":  nil,
	"atlas": nil,
}

func resolveCards(raw string) ([]string, error) {
	want := map[string]bool{}
	for _, part := range strings.Split(raw, ",") {
		name := strings.ToLower(strings.TrimSpace(part))
		if name == "" {
			continue
		}
		if _, known := cardDependencies[name]; !known {
			return nil, fmt.Errorf("unknown AI Deck card %q", name)
		}
		want[name] = true
	}
	if len(want) == 0 {
		return nil, errors.New("at least one card is required")
	}
	var add func(string)
	add = func(name string) {
		for _, dep := range cardDependencies[name] {
			if !want[dep] {
				want[dep] = true
				add(dep)
			}
		}
	}
	for name := range want {
		add(name)
	}
	ordered := []string{"lexicon", "splice", "scry", "trace", "lens", "atlas"}
	out := make([]string, 0, len(want))
	for _, name := range ordered {
		if want[name] {
			out = append(out, name)
		}
	}
	return out, nil
}

func initCommand(args []string) error {
	f := flag.NewFlagSet("lexicon init", flag.ContinueOnError)
	state := f.String("state-root", defaultStateRoot(), "local state root")
	if err := f.Parse(args); err != nil {
		return err
	}
	if len(f.Args()) != 0 {
		return errors.New("init accepts no positional arguments")
	}
	if err := os.MkdirAll(*state, 0o755); err != nil {
		return err
	}
	path := filepath.Join(*state, "canonical-registry.json")
	if _, err := os.Stat(path); err == nil {
		return fmt.Errorf("registry already exists: %s", path)
	}
	r := registry{Version: registryVersion, Global: target{Instance: "global"}, Workspaces: []workspace{}}
	return writeJSON(path, r)
}

func registryCommand(args []string) error {
	if len(args) == 0 {
		return errors.New("registry command required: add-workspace|add-project")
	}
	f := flag.NewFlagSet("lexicon registry", flag.ContinueOnError)
	state := f.String("state-root", defaultStateRoot(), "local state root")
	root := f.String("root", "", "absolute workspace or project root")
	instance := f.String("instance", "", "stable opaque instance identifier")
	workspaceRoot := f.String("workspace-root", "", "owning workspace root for add-project")
	if err := f.Parse(args[1:]); err != nil {
		return err
	}
	if strings.TrimSpace(*root) == "" || strings.TrimSpace(*instance) == "" {
		return errors.New("--root and --instance are required")
	}
	abs, err := filepath.Abs(*root)
	if err != nil {
		return err
	}
	r, path, err := loadRegistry(*state)
	if err != nil {
		return err
	}
	switch args[0] {
	case "add-workspace":
		for _, w := range r.Workspaces {
			if samePath(w.Root, abs) {
				return fmt.Errorf("workspace already registered: %s", abs)
			}
		}
		r.Workspaces = append(r.Workspaces, workspace{Root: abs, Instance: *instance})
	case "add-project":
		if strings.TrimSpace(*workspaceRoot) == "" {
			return errors.New("--workspace-root is required for add-project")
		}
		ws, err := filepath.Abs(*workspaceRoot)
		if err != nil {
			return err
		}
		for wi := range r.Workspaces {
			if !samePath(r.Workspaces[wi].Root, ws) {
				continue
			}
			if !inside(ws, abs) {
				return fmt.Errorf("project root %s is outside workspace %s", abs, ws)
			}
			for _, p := range r.Workspaces[wi].Projects {
				if samePath(p.Root, abs) {
					return fmt.Errorf("project already registered: %s", abs)
				}
			}
			r.Workspaces[wi].Projects = append(r.Workspaces[wi].Projects, project{Root: abs, Instance: *instance})
			return writeJSON(path, r)
		}
		return fmt.Errorf("workspace is not registered: %s", ws)
	default:
		return fmt.Errorf("unknown registry command %q", args[0])
	}
	return writeJSON(path, r)
}

func doctorCommand(args []string) error {
	f := flag.NewFlagSet("lexicon doctor", flag.ContinueOnError)
	bundle := f.String("bundle-root", bundleRoot(), "bundle root")
	state := f.String("state-root", defaultStateRoot(), "local state root")
	cards := f.String("cards", "lexicon", "comma-separated AI Deck cards to verify")
	if err := f.Parse(args); err != nil {
		return err
	}
	selected, err := resolveCards(*cards)
	if err != nil {
		return err
	}
	checks := []string{filepath.Join(*bundle, "bin", executable("aideck"))}
	needLua := false
	for _, card := range selected {
		switch card {
		case "lexicon":
			checks = append(checks, filepath.Join(*bundle, "bin", executable("lexicon-mcp")), filepath.Join(*bundle, "bin", executable("lexicon-codex")), filepath.Join(*bundle, "apps", "lexicon", "application", "pulp.app.toml"), filepath.Join(*state, "canonical-registry.json"))
			needLua = true
		case "splice":
			checks = append(checks, filepath.Join(*bundle, "bin", executable("splice")), filepath.Join(*bundle, "bin", executable("splice-mcp")), filepath.Join(*bundle, "apps", "splice", "application", "pulp.app.toml"), filepath.Join(*bundle, "apps", "splice", "engines", "bounded-transform-cell", "bounded-transform.wasm"))
			needLua = true
		case "scry":
			checks = append(checks, filepath.Join(*bundle, "bin", executable("scry")), filepath.Join(*bundle, "apps", "scry", "application", "pulp.app.toml"), filepath.Join(*bundle, "apps", "pulp-engines", "lifecycle-cell", "lifecycle-evaluator.wasm"))
			needLua = true
		case "trace":
			checks = append(checks, filepath.Join(*bundle, "bin", executable("trace")), filepath.Join(*bundle, "apps", "trace", "application", "pulp.app.toml"), filepath.Join(*bundle, "apps", "pulp-engines", "receipt-sqlite-cell", "receipt-sqlite.wasm"))
			needLua = true
		case "lens":
			checks = append(checks, filepath.Join(*bundle, "bin", executable("lens")), filepath.Join(*bundle, "bin", executable("lens-mcp")), filepath.Join(*bundle, "apps", "lens", "nvim", "lua", "inspector", "init.lua"))
		case "atlas":
			checks = append(checks, filepath.Join(*bundle, "bin", executable("atlas")))
		}
	}
	if needLua {
		checks = append(checks, filepath.Join(*bundle, "apps", "Pulp-Lua", "pulp-cell", "lua-orchestrator.wasm"))
	}
	for _, path := range checks {
		if info, err := os.Stat(path); err != nil || info.IsDir() {
			return fmt.Errorf("missing required bundle/state file: %s", path)
		}
	}
	if containsCard(selected, "lexicon") {
		if _, _, err := loadRegistry(*state); err != nil {
			return err
		}
	}
	return json.NewEncoder(os.Stdout).Encode(map[string]any{"version": "lexicon.doctor.v1", "ok": true, "bundle_root": *bundle, "state_root": *state, "cards": selected})
}

func containsCard(cards []string, want string) bool {
	for _, card := range cards {
		if card == want {
			return true
		}
	}
	return false
}

func loadRegistry(state string) (registry, string, error) {
	path := filepath.Join(state, "canonical-registry.json")
	b, err := os.ReadFile(path)
	if err != nil {
		return registry{}, path, err
	}
	var r registry
	if err := json.Unmarshal(b, &r); err != nil {
		return registry{}, path, fmt.Errorf("decode registry: %w", err)
	}
	if r.Version != registryVersion || strings.TrimSpace(r.Global.Instance) == "" {
		return registry{}, path, errors.New("invalid registry")
	}
	return r, path, nil
}
func writeJSON(path string, value any) error {
	b, err := json.MarshalIndent(value, "", "  ")
	if err != nil {
		return err
	}
	tmp := path + ".tmp-" + fmt.Sprint(time.Now().UnixNano())
	if err := os.WriteFile(tmp, append(b, '\n'), 0o600); err != nil {
		return err
	}
	return os.Rename(tmp, path)
}
func defaultStateRoot() string {
	if runtime.GOOS == "windows" {
		if local := os.Getenv("LOCALAPPDATA"); local != "" {
			return filepath.Join(local, "Lexicon")
		}
	}
	if xdg := os.Getenv("XDG_DATA_HOME"); xdg != "" {
		return filepath.Join(xdg, "lexicon")
	}
	home, _ := os.UserHomeDir()
	return filepath.Join(home, ".local", "share", "lexicon")
}
func defaultNvimConfig() string {
	if runtime.GOOS == "windows" {
		return filepath.Join(os.Getenv("LOCALAPPDATA"), "nvim")
	}
	home, _ := os.UserHomeDir()
	return filepath.Join(home, ".config", "nvim")
}
func bundleRoot() string {
	exe, err := os.Executable()
	if err != nil {
		return "."
	}
	return filepath.Dir(filepath.Dir(exe))
}
func executable(name string) string {
	if runtime.GOOS == "windows" {
		return name + ".exe"
	}
	return name
}
func samePath(a, b string) bool {
	if runtime.GOOS == "windows" {
		return strings.EqualFold(filepath.Clean(a), filepath.Clean(b))
	}
	return filepath.Clean(a) == filepath.Clean(b)
}
func inside(root, child string) bool {
	rel, err := filepath.Rel(root, child)
	return err == nil && rel != ".." && !strings.HasPrefix(rel, ".."+string(filepath.Separator))
}
